// Builds server/knowledge/index.js from the markdown files in server/knowledge/docs/.
// Run: node server/knowledge/build.mjs
// Only documents with `visibility: public-approved` in their front-matter are indexed. Everything else stays out.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Lines that look like instructions to a model are never indexed; a human must review them.
const SUSPICIOUS = /ignore (all |any )?(previous|prior|above)|disregard .{0,20}(instruction|rule)|system prompt|api[\s-]?key|you are now|reveal your/i;
const MAX_CHUNK = 900;

export function parseDoc(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) return { meta: {}, body: text };
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const i = line.indexOf(":");
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { meta, body: m[2] };
}

function chunkBody(body) {
  const out = [];
  for (const part of body.split(/\n(?=#{1,3} )/)) {
    const h = part.match(/^#{1,3} (.*)\n?/);
    const section = h ? h[1].trim() : "";
    let cur = "";
    for (const para of part.replace(/^#{1,3} .*\n?/, "").split(/\n{2,}/)) {
      if (cur && cur.length + para.length > MAX_CHUNK) {
        out.push({ section, text: cur.trim() });
        cur = "";
      }
      cur += `${para}\n\n`;
    }
    if (cur.trim()) out.push({ section, text: cur.trim() });
  }
  return out;
}

export function buildIndex(dir) {
  const chunks = [];
  const skipped = [];
  if (!fs.existsSync(dir)) return { chunks, skipped };
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".md") && f.toLowerCase() !== "readme.md")) {
    const { meta, body } = parseDoc(fs.readFileSync(path.join(dir, file), "utf8"));
    if (meta.visibility !== "public-approved") {
      skipped.push({ file, reason: `visibility is "${meta.visibility || "missing"}", not public-approved` });
      continue;
    }
    const docId = meta.id || file.replace(/\.md$/, "");
    chunkBody(body).forEach((c, i) => {
      if (SUSPICIOUS.test(c.text)) {
        skipped.push({ file, reason: `chunk ${i} looks like a prompt injection; review it` });
        return;
      }
      chunks.push({
        id: `${docId}#${i}`,
        docId,
        title: meta.title || docId,
        projectId: meta.projectId || "",
        verification: meta.verification || "unverified",
        section: c.section,
        text: c.text,
      });
    });
  }
  return { chunks, skipped };
}

// CLI
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const { chunks, skipped } = buildIndex(path.join(here, "docs"));
  fs.writeFileSync(path.join(here, "index.js"), `// Generated by build.mjs. Do not edit.\nexport default ${JSON.stringify(chunks, null, 1)};\n`);
  console.log(`indexed ${chunks.length} chunks`);
  for (const s of skipped) console.log(`skipped ${s.file}: ${s.reason}`);
}
